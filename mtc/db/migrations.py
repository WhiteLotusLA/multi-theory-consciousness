"""
PostgreSQL Migrations
=====================

Renders the canonical ``migrations/postgres/*.sql`` files from the schema
registry, so the SQL has one source: the ``*_SCHEMA_SQL`` constants that
``mtc.core.schema_registry.SCHEMA_ARTIFACTS["postgres"]`` lists.

- ``MIGRATION_FILES`` assigns every registered PostgreSQL artifact to exactly
  one file: ``001_core_schema.sql`` (episodic and core memory, then the
  conversation repository), ``002_research_schema.sql`` (snapshots and events)
  and ``003_safety_schema.sql`` (the safety audit).
- Each file opens with comment lines naming the generator, the source
  constants, that every statement is idempotent and safe to re-run, and that
  PostgreSQL 14 or later needs no extension; then the statements in the order
  the constants define, each dedented, ending in one semicolon and followed by
  a blank line. No date, author or machine detail appears.
- ``statements_in_order`` is the list the bootstrap applies (the same
  statements, in file order) and ``expected_names`` the tables and indexes
  the verifier expects, parsed from the same statements.

Usage: ``python3 -m mtc.db.migrations [--write | --check] [--dir DIR]``.
``--write`` writes the files into ``DIR`` (default ``migrations/postgres``
under the working directory); ``--check`` writes nothing and exits 1 when a
committed file is missing, differs or is not produced by the registry.

No config key is read; no store is contacted. The statements create tables
and indexes only: no drop, password, seed row or extension.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Sequence, Tuple

from mtc.core.schema_registry import SCHEMA_ARTIFACTS, load_artifact

MIGRATIONS_DIR = Path("migrations/postgres")
GENERATOR_COMMAND = "python3 -m mtc.db.migrations --write"

MIGRATION_FILES: Tuple[Tuple[str, Tuple[str, ...]], ...] = (
    (
        "001_core_schema.sql",
        (
            "mtc.memory.episodic_store.EPISODIC_SCHEMA_SQL",
            "mtc.memory.conversation_store.CONVERSATION_SCHEMA_SQL",
        ),
    ),
    ("002_research_schema.sql", ("mtc.memory.postgres_stores.RESEARCH_SCHEMA_SQL",)),
    ("003_safety_schema.sql", ("mtc.safety.stores.SAFETY_SCHEMA_SQL",)),
)

_TABLE = re.compile(r"^\s*CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)", re.IGNORECASE)
_INDEX = re.compile(
    r"^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+(\w+)", re.IGNORECASE
)


def _check_assignment() -> None:
    registered = list(SCHEMA_ARTIFACTS["postgres"])
    assigned = [path for _, paths in MIGRATION_FILES for path in paths]
    if sorted(registered) != sorted(assigned) or len(set(assigned)) != len(assigned):
        raise RuntimeError(
            "MIGRATION_FILES must assign every registered PostgreSQL artifact to "
            f"exactly one file; registered {registered}, assigned {assigned}"
        )


def normalize_statement(statement: str) -> str:
    """Dedent and strip a statement and end it with exactly one semicolon."""
    text = textwrap.dedent(statement).strip()
    while text.endswith(";"):
        text = text[:-1].rstrip()
    return f"{text};"


def _file_statements(filename: str) -> List[str]:
    for name, paths in MIGRATION_FILES:
        if name == filename:
            statements: List[str] = []
            for dotted in paths:
                statements.extend(
                    normalize_statement(item) for item in load_artifact(dotted)
                )
            return statements
    known = ", ".join(name for name, _ in MIGRATION_FILES)
    raise ValueError(f"unknown migration {filename!r}; known: {known}")


def _header(filename: str) -> List[str]:
    paths = dict(MIGRATION_FILES)[filename]
    lines = [
        f"-- {filename}",
        f"-- GENERATED by `{GENERATOR_COMMAND}`; do not edit by hand.",
        "-- Source constants, in order (registered in",
        '-- mtc.core.schema_registry.SCHEMA_ARTIFACTS["postgres"]):',
    ]
    lines += [f"--   {dotted}" for dotted in paths]
    lines += [
        "-- Every statement is CREATE ... IF NOT EXISTS: idempotent and safe to",
        "-- re-run. PostgreSQL 14 or later; no extension is needed.",
    ]
    return lines


def render_migration(filename: str) -> str:
    """Return the full text of one migration file."""
    _check_assignment()
    statements = _file_statements(filename)
    parts = ["\n".join(_header(filename)), ""]
    for statement in statements:
        parts.append(statement)
        parts.append("")
    return "\n".join(parts)


def render_all() -> Dict[str, str]:
    """Every migration file name mapped to its rendered text, in file order."""
    return {name: render_migration(name) for name, _ in MIGRATION_FILES}


def statements_in_order() -> List[str]:
    """Every statement of every migration, in file order (what bootstrap runs)."""
    _check_assignment()
    statements: List[str] = []
    for name, _ in MIGRATION_FILES:
        statements.extend(_file_statements(name))
    return statements


def expected_names(
    statements: Optional[Sequence[str]] = None,
) -> Tuple[FrozenSet[str], FrozenSet[str]]:
    """The table and index names the statements create, as two sets."""
    source = statements if statements is not None else statements_in_order()
    tables = set()
    indexes = set()
    for statement in source:
        table = _TABLE.match(statement)
        if table:
            tables.add(table.group(1).lower())
            continue
        index = _INDEX.match(statement)
        if index:
            indexes.add(index.group(1).lower())
    return frozenset(tables), frozenset(indexes)


def check_dir(directory: Path) -> List[str]:
    """File names in ``directory`` that are missing, differ or are not rendered."""
    rendered = render_all()
    drift = []
    for name, text in rendered.items():
        path = directory / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            drift.append(name)
    if directory.is_dir():
        for path in sorted(directory.glob("*.sql")):
            if path.name not in rendered:
                drift.append(path.name)
    return drift


def write_dir(directory: Path) -> List[str]:
    """Write every rendered file into ``directory``; return the names written."""
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render_all().items():
        path = directory / name
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.write_text(text, encoding="utf-8")
        written.append(name)
    return written


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python3 -m mtc.db.migrations",
        description="Render migrations/postgres/*.sql from the schema registry.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the files")
    mode.add_argument("--check", action="store_true", help="report drift, exit 1")
    parser.add_argument(
        "--dir",
        type=Path,
        default=MIGRATIONS_DIR,
        help="migrations directory (default: migrations/postgres)",
    )
    args = parser.parse_args(argv)
    if args.check:
        drift = check_dir(args.dir)
        for name in drift:
            print(f"DRIFT: {args.dir / name}")
        if drift:
            print(f"regenerate with: {GENERATOR_COMMAND}")
        return 1 if drift else 0
    for name in write_dir(args.dir):
        print(f"wrote {args.dir / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
